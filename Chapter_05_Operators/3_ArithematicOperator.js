let a = 10;
let b = 3;

// Arithmetic Operators
let sum = a + b;
let sub = a - b;
let mul = a * b;
let div = a / b;

console.log("Sum: " + sum);
console.log("Sub: " + sub);
console.log("Mul: " + mul);
console.log("Div: " + div);

// Modulus operator

let mod = a % b;
console.log("Mod: " + mod);

// n%2 == 0 => even number
// n%2 ==1 => odd number

// Exponential operator
let exp = a ** b;
console.log("Exp: " + exp);

