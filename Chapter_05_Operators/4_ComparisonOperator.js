// Comparison Operators (will always return boolean value true or false)
// ==, ===, !=, !==, >, <, >=, <=

console.log(10 > 9); //true 
console.log(10 < 9); // false
console.log(10 >= 10); //true (10 > 10 OR 10 == 10)
console.log(10 <= 10); //true (10 < 10 OR 10 == 10)

// Difference between == and ===
// == => checks only value (loose comparison)
// === => checks value and data type (strict comparison)
console.log("difference between == and ===");
console.log(10 == "10"); 
console.log(10 === "10"); 


